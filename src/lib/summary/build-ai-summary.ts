import { categoryFromPath } from "@/lib/core/paths";
import type { FileAnalysis, NodeCategory, ProjectSnapshot, SymbolRecord } from "@/lib/types/ir";

const ROLE_LABELS: Record<NodeCategory, string> = {
  frontend: "frontend",
  backend: "backend",
  route: "route",
  service: "service",
  utility: "utility",
  model: "model",
  config: "config",
  external: "external",
  unknown: "file",
};

const MAX_LISTED = 8;
const DESCRIBABLE_LANGUAGES = new Set(["typescript", "tsx", "javascript", "jsx", "prisma"]);

function capList(items: string[]): string {
  if (items.length <= MAX_LISTED) return items.join(", ");
  return `${items.slice(0, MAX_LISTED).join(", ")}, +${items.length - MAX_LISTED} more`;
}

function describeSymbol(symbol: SymbolRecord): string {
  return `${symbol.kind} ${symbol.name}`;
}

function fileSection(
  file: FileAnalysis,
  incoming: Map<string, Set<string>>,
): string {
  const lines: string[] = [];
  lines.push(`### ${file.path} (${file.language}, ${file.lines} lines, ${ROLE_LABELS[categoryFromPath(file.path)]})`);

  if (file.status === "error") {
    lines.push(`- Could not be parsed: ${file.errorMessage ?? "unknown error"}`);
    return lines.join("\n");
  }

  if (file.routes.length > 0) {
    const routes = file.routes.map((route) => `${route.method} ${route.path}`);
    lines.push(`- Routes: ${capList(routes)}`);
  }

  const topLevelExports = file.symbols.filter((symbol) => symbol.exported && symbol.parentId === null);
  if (topLevelExports.length > 0) {
    lines.push(`- Exports: ${capList(topLevelExports.map(describeSymbol))}`);
  }

  const internalImports = file.imports.filter((item) => item.resolvedPath);
  const externalImports = [...new Set(file.imports.filter((item) => !item.resolvedPath).map((item) => item.specifier))];
  if (internalImports.length > 0) {
    lines.push(`- Imports: ${capList(internalImports.map((item) => item.resolvedPath as string))}`);
  }
  if (externalImports.length > 0) {
    lines.push(`- Uses packages: ${capList(externalImports)}`);
  }

  const usedBy = incoming.get(file.path);
  if (usedBy && usedBy.size > 0) {
    lines.push(`- Used by: ${capList([...usedBy].sort())}`);
  }

  if (lines.length === 1) {
    lines.push("- No exports, routes or internal imports detected.");
  }

  return lines.join("\n");
}

export function buildAiSummary(snapshot: ProjectSnapshot): string {
  const { detection, stats } = snapshot;
  const incoming = new Map<string, Set<string>>();
  for (const dep of snapshot.dependencies) {
    let set = incoming.get(dep.to);
    if (!set) {
      set = new Set<string>();
      incoming.set(dep.to, set);
    }
    set.add(dep.from);
  }

  const describableFiles = snapshot.files
    .filter((file) => DESCRIBABLE_LANGUAGES.has(file.language) && file.status !== "metadata" && file.status !== "skipped")
    .sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));

  const parts: string[] = [];
  parts.push(`# ${snapshot.name} — AI context summary`);
  parts.push(
    "This document describes what lives in each source file, generated by TraceMyProject's static analysis " +
      "(no source code was executed or sent anywhere). Paste it into an AI assistant so that, instead of guessing, " +
      "it can tell you exactly which file(s) to open, paste, or edit to answer a question about this codebase.",
  );

  parts.push("## Project");
  parts.push(
    [
      `- Frameworks: ${detection.frameworks.length > 0 ? detection.frameworks.join(", ") : "none detected"}`,
      `- Languages: ${detection.languages.length > 0 ? detection.languages.join(", ") : "none detected"}`,
      `- Package manager: ${detection.packageManager ?? "unknown"}`,
      `- Entry points: ${detection.entryPoints.length > 0 ? detection.entryPoints.join(", ") : "none detected"}`,
      `- Files: ${stats.files} total, ${stats.analyzedFiles} analyzed · Lines: ${stats.totalLines} · Routes: ${stats.routes} · Circular deps: ${stats.cycles}`,
    ].join("\n"),
  );

  if (snapshot.cycles.length > 0) {
    parts.push("## Circular dependencies");
    parts.push(snapshot.cycles.map((cycle) => `- ${cycle.join(" ↔ ")}`).join("\n"));
  }

  parts.push("## Files");
  parts.push(describableFiles.map((file) => fileSection(file, incoming)).join("\n\n"));

  return parts.join("\n\n") + "\n";
}

export function estimateTokenCount(text: string): number {
  return Math.ceil(text.length / 4);
}
